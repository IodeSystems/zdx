package mcpcmd

import (
	"strings"
	"testing"
)

// TestRejectGeneratedFileWrite locks in the codegen-output blocklist. If a
// new generator is added (or one is removed), this test should be updated
// alongside the generatedFilePatterns list — they share one source of truth.
func TestRejectGeneratedFileWrite(t *testing.T) {
	t.Parallel()

	cases := []struct {
		name     string
		path     string
		wantErr  bool
		wantHint string // substring expected in the error message (when wantErr)
	}{
		// Blocked — codegen outputs.
		{"sqlc sql.go", "internal/db/todos.sql.go", true, "sqlc"},
		{"sqlc metaquery", "internal/db/todos.sql.metaquery.go", true, "metaquery: off"},
		{"sqlc querier", "internal/db/querier.go", true, "sqlc"},
		{"sqlc models", "internal/db/models.go", true, "sqlc"},
		{"oapi-codegen models", "internal/dxclient/models.gen.go", true, "oapi-codegen"},
		{"openapi-typescript", "ui/src/api.gen.ts", true, "openapi-typescript"},
		{"shipped.sql", "schema/shipped.sql", true, "pg_dump"},
		// Normalized variants — agents may pass leading "./" or backslashes.
		{"sqlc sql.go with ./", "./internal/db/todos.sql.go", true, "sqlc"},

		// Allowed — sources of truth and unrelated paths.
		{"sql source", "queries/todos.sql", false, ""},
		{"handler source", "internal/server/handlers/handlers_doctor.go", false, ""},
		{"migration source", "internal/migrate/sql/162_x.up.sql", false, ""},
		{"openapi.json (intent)", "internal/dxclient/openapi.json", false, ""},
		{"random go file", "internal/cli/agent/manager.go", false, ""},
		{"random ts file", "ui/src/components/Foo.tsx", false, ""},
		// internal/db/ files that are NOT generated by sqlc (sqlc only emits
		// *.sql.go, *.sql.metaquery.go, querier.go, models.go) must not be
		// blocked or hand-written DB helpers become unreachable.
		{"hand-written db helper", "internal/db/helpers.go", false, ""},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			err := rejectGeneratedFileWrite(tc.path)
			if tc.wantErr {
				if err == nil {
					t.Fatalf("expected error for %s, got nil", tc.path)
				}
				if tc.wantHint != "" && !strings.Contains(err.Error(), tc.wantHint) {
					t.Errorf("error for %s missing hint %q: %v", tc.path, tc.wantHint, err)
				}
			} else {
				if err != nil {
					t.Fatalf("unexpected error for %s: %v", tc.path, err)
				}
			}
		})
	}
}
