package doctor

import (
	"fmt"
	"strings"
)

// RenderDevDockerfile emits a starter dev.Dockerfile for the given stack.
// The output is opinionated — tweak after generation.
func RenderDevDockerfile(s Stack) string {
	var b strings.Builder
	b.WriteString("# Auto-generated by `dx doctor --fix`. Tweak to taste.\n")

	switch {
	case s.HasGo:
		fmt.Fprintf(&b, "FROM golang:%s-bookworm\n\n", s.GoVersion)
	case s.HasNode:
		fmt.Fprintf(&b, "FROM node:%s-bookworm\n\n", s.NodeVersion)
	case s.HasPython:
		fmt.Fprintf(&b, "FROM python:%s-slim\n\n", s.PythonMinor)
	default:
		b.WriteString("FROM debian:bookworm-slim\n\n")
	}

	aptPkgs := []string{"ca-certificates", "curl", "git"}
	if s.HasPostgres {
		aptPkgs = append(aptPkgs, "postgresql-client")
	}
	if s.HasGo && s.HasNode {
		aptPkgs = append(aptPkgs, "gnupg")
	}
	if len(aptPkgs) > 0 {
		b.WriteString("RUN apt-get update \\\n")
		b.WriteString(" && apt-get install -y --no-install-recommends \\\n")
		for _, p := range aptPkgs {
			fmt.Fprintf(&b, "    %s \\\n", p)
		}
		b.WriteString(" && rm -rf /var/lib/apt/lists/*\n\n")
	}

	if s.HasGo && s.HasNode {
		b.WriteString("# Node.js (frontend build)\n")
		fmt.Fprintf(&b, "RUN curl -fsSL https://deb.nodesource.com/setup_%s.x | bash - \\\n", s.NodeVersion)
		b.WriteString(" && apt-get install -y --no-install-recommends nodejs \\\n")
		b.WriteString(" && rm -rf /var/lib/apt/lists/*\n\n")
	}

	if s.HasGo && s.HasSqlc {
		b.WriteString("# sqlc (query codegen)\n")
		b.WriteString("RUN go install github.com/sqlc-dev/sqlc/cmd/sqlc@latest\n\n")
	}

	// Agent-runtime defaults — see dev.Dockerfile commentary in zdx-go for
	// the rationale. /workspace/bin is the per-slot dx + dx-agent seed
	// location; GOPATH/GOMODCACHE point at writable /tmp paths so go
	// build/test don't trip on the default user-home cache permissions.
	// Emitting only for Go stacks keeps the non-Go images minimal.
	if s.HasGo {
		b.WriteString("ENV PATH=/workspace/bin:/usr/local/go/bin:/go/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \\\n")
		b.WriteString("    GOPATH=/tmp/gopath \\\n")
		b.WriteString("    GOMODCACHE=/tmp/gomodcache\n")
		b.WriteString("RUN mkdir -p /tmp/gopath /tmp/gomodcache\n\n")
	}

	b.WriteString("WORKDIR /workspace\n")
	b.WriteString("COPY . /workspace\n\n")
	b.WriteString("CMD [\"bash\"]\n")
	return b.String()
}
