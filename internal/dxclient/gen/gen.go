// Package gen produces the oapi-codegen input for internal/dxclient.
//
// Huma emits OpenAPI 3.1, which oapi-codegen v2 does not fully support. These
// helpers downgrade the spec to 3.0 (primarily rewriting `type: [X, null]` as
// `type: X, nullable: true`) and shell out to oapi-codegen against the
// downgraded spec.
//
// Callers need oapi-codegen on PATH:
//
//	go install github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@latest
package gen

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// Generate downgrades the 3.1 spec at specPath to 3.0 and invokes oapi-codegen
// using configPath. Returns the output file path parsed from the config.
func Generate(specPath, configPath string) (string, error) {
	specBytes, err := os.ReadFile(specPath)
	if err != nil {
		return "", fmt.Errorf("read spec: %w", err)
	}

	downgraded, err := Downgrade31To30(specBytes)
	if err != nil {
		return "", fmt.Errorf("downgrade spec: %w", err)
	}

	tmp, err := os.CreateTemp("", "zdx-openapi-*.json")
	if err != nil {
		return "", fmt.Errorf("create temp: %w", err)
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(downgraded); err != nil {
		tmp.Close()
		return "", fmt.Errorf("write temp: %w", err)
	}
	tmp.Close()

	bin := codegenBin()
	cmd := exec.Command(bin, "-config", configPath, tmp.Name())
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("oapi-codegen: %w (ensure it is on PATH: go install github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@latest)", err)
	}

	outPath := readOutputPath(configPath)

	// Post-process: deduplicate response types. Huma names schema types
	// XxxResponse; oapi-codegen's client also generates XxxResponse wrappers.
	// Rename the client's wrappers to ParsedXxxResponse to avoid collisions.
	if outPath != "" {
		if err := deduplicateResponseTypes(outPath); err != nil {
			return "", fmt.Errorf("dedup response types: %w", err)
		}
	}

	return outPath, nil
}

func codegenBin() string {
	if p, err := exec.LookPath("oapi-codegen"); err == nil {
		return p
	}
	if home, err := os.UserHomeDir(); err == nil {
		candidate := filepath.Join(home, "go", "bin", "oapi-codegen")
		if _, err := os.Stat(candidate); err == nil {
			return candidate
		}
	}
	return "oapi-codegen"
}

func readOutputPath(configPath string) string {
	b, err := os.ReadFile(configPath)
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(b), "\n") {
		if rest, ok := strings.CutPrefix(line, "output:"); ok {
			return strings.TrimSpace(rest)
		}
	}
	return ""
}

// Downgrade31To30 rewrites an OpenAPI 3.1 document into a 3.0-compatible form
// suitable for oapi-codegen v2. It handles the only 3.1 construct Huma emits
// today: union-style nullability (`type: [X, null]` → `type: X, nullable: true`).
// If Huma starts emitting other 3.1-specific keywords (unevaluatedProperties,
// dependentSchemas, const, etc.), extend this function.
func Downgrade31To30(src []byte) ([]byte, error) {
	var doc map[string]any
	if err := json.Unmarshal(src, &doc); err != nil {
		return nil, err
	}
	doc["openapi"] = "3.0.3"
	walk(doc)
	return json.Marshal(doc)
}

// deduplicateResponseTypes finds response wrapper types generated by the
// oapi-codegen client that collide with schema model types, and renames
// the client's wrappers by adding a "Parsed" prefix.
func deduplicateResponseTypes(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}

	// Find all "type XxxResponse struct" declarations.
	typeRe := regexp.MustCompile(`(?m)^type (\w+Response) struct \{`)
	matches := typeRe.FindAllStringSubmatch(string(data), -1)

	// Count occurrences of each name.
	counts := map[string]int{}
	for _, m := range matches {
		counts[m[1]]++
	}

	// For names declared more than once, rename the SECOND occurrence
	// (the client wrapper) and all references to it.
	src := string(data)
	for name, count := range counts {
		if count < 2 {
			continue
		}
		newName := "Parsed" + name
		// Replace the second declaration and its references.
		// Strategy: find the byte offset of the second declaration,
		// then replace that name everywhere after it.
		first := strings.Index(src, "type "+name+" struct {")
		if first < 0 {
			continue
		}
		rest := src[first+1:]
		second := strings.Index(rest, "type "+name+" struct {")
		if second < 0 {
			continue
		}
		splitAt := first + 1 + second
		before := src[:splitAt]
		after := src[splitAt:]
		after = strings.ReplaceAll(after, name, newName)
		// Also fix interface references in the before section that point to the wrapper.
		// The interface declares: XxxWithResponse(...) (*XxxResponse, error)
		// These should point to the renamed type.
		before = strings.ReplaceAll(before, "(*"+name+", error)", "(*"+newName+", error)")
		src = before + after
	}

	// Revert over-eager renames: the blanket replace above also rewrote the
	// wrapper's JSON<N> body-type field and the ParseParsedXxxResponse function's
	// `var dest XxxResponse` — both of which must point to the body type, not the
	// wrapper. Without this, json.Unmarshal targets the wrapper (which has no
	// schema fields) and JSON200 comes back empty.
	src = regexp.MustCompile(`(?m)^(\s+JSON\d+\s+\*)Parsed(\w+Response)$`).
		ReplaceAllString(src, "${1}${2}")
	src = regexp.MustCompile(`(?m)^(\s+var dest )Parsed(\w+Response)$`).
		ReplaceAllString(src, "${1}${2}")

	return os.WriteFile(path, []byte(src), 0644)
}

func walk(v any) {
	switch x := v.(type) {
	case map[string]any:
		if t, ok := x["type"]; ok {
			if arr, ok := t.([]any); ok {
				primary := ""
				nullable := false
				for _, e := range arr {
					s, ok := e.(string)
					if !ok {
						continue
					}
					if s == "null" {
						nullable = true
						continue
					}
					if primary == "" {
						primary = s
					}
				}
				if primary == "" {
					primary = "object"
				}
				x["type"] = primary
				if nullable {
					x["nullable"] = true
				}
			}
		}
		for _, vv := range x {
			walk(vv)
		}
	case []any:
		for _, vv := range x {
			walk(vv)
		}
	}
}
